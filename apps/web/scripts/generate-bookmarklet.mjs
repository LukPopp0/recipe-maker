// Bundles shared/src/capture/bookmarklet-entry.ts into a minified IIFE and writes it
// to src/generated/bookmarklet-source.ts (gitignored) for lib/bookmarklet.ts.
import { build } from 'vite';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const entry = resolve(here, '../../../shared/src/capture/bookmarklet-entry.ts');
const outFile = resolve(here, '../src/generated/bookmarklet-source.ts');

const result = await build({
  configFile: false,
  logLevel: 'warn',
  build: {
    write: false,
    minify: true,
    lib: { entry, formats: ['iife'], name: 'RecipeMakerBookmarklet', fileName: 'bookmarklet' },
  },
});

const outputs = Array.isArray(result) ? result.flatMap((r) => r.output) : result.output;
const chunk = outputs.find((o) => o.type === 'chunk');
if (!chunk) throw new Error('bookmarklet build produced no chunk');
// The minifier emits template literals; force a double-quoted literal for the origin token.
const code = chunk.code.trim().replace('`__RECIPE_MAKER_ORIGIN__`', '"__RECIPE_MAKER_ORIGIN__"');

if (code.split('__RECIPE_MAKER_ORIGIN__').length !== 2) {
  throw new Error('bookmarklet origin token must appear exactly once');
}
if (!code.includes('"__RECIPE_MAKER_ORIGIN__"')) {
  throw new Error('bookmarklet origin token must be a double-quoted string literal');
}
if (/^\s*(import|export)\s/m.test(code)) {
  throw new Error('bookmarklet output must not contain module syntax');
}

await mkdir(dirname(outFile), { recursive: true });
await writeFile(
  outFile,
  `// GENERATED by apps/web/scripts/generate-bookmarklet.mjs - do not edit.\n` +
    `export const BOOKMARKLET_SOURCE: string = ${JSON.stringify(code)};\n`,
);
console.log(`generated ${outFile} (${code.length} bytes)`);
